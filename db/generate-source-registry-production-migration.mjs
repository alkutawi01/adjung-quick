// generate-source-registry-production-migration.mjs — Backend Control
// Plane Phase 1, PRODUCTION data migration GENERATOR.
//
// Per the approved cutover plan §3 (docs/backend-control-plane-phase1-source-registry-production-cutover-plan-v1.md,
// commit c8e3968) and ChatGPT's explicit go-ahead (2026-08-16): "tulis
// migration script sahaja. Jangan jalankan terhadap production lagi."
//
// This script does NOT touch any database. It reads RSS_SOURCES from
// lab/sources.js (the only input), validates it fail-closed, and WRITES
// a reviewable .sql file to db/generated/. That file — not this script —
// is what eventually gets pasted into Supabase SQL Editor, and only
// after a separate, explicit production-execution approval.
//
// Scope, per ChatGPT's exact instruction:
//   - production `sources` migration only
//   - single transaction (BEGIN...COMMIT in the generated SQL)
//   - UPDATE existing 43 rows, never INSERT
//   - populate only the new columns (status, known_category, source_type,
//     exclude_patterns, extra_ca, active, updated_at)
//   - never touch coverage, last_success_at, last_failure_at,
//     last_failure_reason (existing operational columns)
//   - preserve exact id/url identity
//   - preserve rss-kpm = disabled
//   - set active consistent with status (§4a)
//   - fail-closed if any of the 43 sources don't validate
//   - URL validation
//   - zero partial migration (wrapped in one transaction + a row-count
//     assertion inside the same transaction)
//
// Usage:
//   node db/generate-source-registry-production-migration.mjs
//
// This performs ONLY local validation + file generation — no
// SUPABASE_URL/key needed, no network call, nothing written to any DB.

import { writeFileSync, mkdirSync } from 'fs';
import { RSS_SOURCES } from '../lab/sources.js';

function fail(msg) {
  console.error(`FAIL-CLOSED — ${msg}`);
  process.exit(1);
}

console.log(`\nSOURCE REGISTRY PRODUCTION MIGRATION — generator (no DB access)\n`);
console.log(`${RSS_SOURCES.length} entries in lab/sources.js.\n`);

// --- Duplicate-id check ---
const idCounts = new Map();
for (const s of RSS_SOURCES) idCounts.set(s.id, (idCounts.get(s.id) ?? 0) + 1);
const dupes = [...idCounts.entries()].filter(([, count]) => count > 1);
if (dupes.length > 0) {
  fail(`duplicate ids within lab/sources.js itself: ${dupes.map(([id, c]) => `${id} (${c}x)`).join(', ')}`);
}

// --- URL validation ---
const badUrls = RSS_SOURCES.filter(s => {
  try { new URL(s.url); return false; } catch { return true; }
});
if (badUrls.length > 0) {
  fail(`invalid URL(s): ${badUrls.map(s => `${s.id}="${s.url}"`).join(', ')}`);
}

// --- status/active consistency check, per §4a ---
const rows = RSS_SOURCES.map(s => {
  const status = s.status ?? 'active';
  if (!['active', 'disabled', 'archived'].includes(status)) {
    fail(`${s.id}: unrecognized status "${status}"`);
  }
  return {
    id: s.id,
    name: s.name,
    url: s.url,
    language: s.language,
    trustScore: s.trustScore,
    knownCategory: s.knownCategory ?? null,
    sourceType: s.sourceType ?? null,
    excludePatterns: s.excludePatterns ? s.excludePatterns.map(String) : null,
    extraCa: s.extraCa ?? null,
    status,
    active: status === 'active',
  };
});

const disabledRows = rows.filter(r => r.status !== 'active');
if (!(disabledRows.length === 1 && disabledRows[0].id === 'rss-kpm')) {
  fail(`expected exactly rss-kpm to be non-active; found: ${disabledRows.map(r => `${r.id}=${r.status}`).join(', ') || '(none)'}. RSS_SOURCES may have changed since the cutover plan's baseline (§1) — investigate before proceeding.`);
}

console.log('All validations passed:');
console.log(`  ${rows.length} sources, ${rows.length - disabledRows.length} active, ${disabledRows.length} non-active (rss-kpm, disabled) — matches cutover plan §1 baseline.\n`);

// --- SQL generation ---
function sqlString(v) {
  if (v === null || v === undefined) return 'NULL';
  return `'${String(v).replace(/'/g, "''")}'`;
}
function sqlStringArray(arr) {
  if (!arr || arr.length === 0) return 'NULL';
  return `ARRAY[${arr.map(sqlString).join(', ')}]::TEXT[]`;
}

const updateStatements = rows.map(r => `UPDATE sources SET
  status = ${sqlString(r.status)},
  known_category = ${sqlString(r.knownCategory)},
  source_type = ${sqlString(r.sourceType)},
  exclude_patterns = ${sqlStringArray(r.excludePatterns)},
  extra_ca = ${sqlString(r.extraCa)},
  active = ${r.active},
  updated_at = now()
WHERE id = ${sqlString(r.id)};`).join('\n\n');

const idList = rows.map(r => sqlString(r.id)).join(', ');

const sql = `-- generated-source-registry-production-migration.sql
-- AUTO-GENERATED by db/generate-source-registry-production-migration.mjs
-- from lab/sources.js — DO NOT hand-edit. Re-run the generator if
-- RSS_SOURCES changes.
--
-- Per cutover plan §3 (commit c8e3968): UPDATE-only against the ${rows.length}
-- rows that already exist in production \`sources\` (never INSERT).
-- Populates ONLY the new columns approved in
-- db/schema-source-registry-production-v1.sql — coverage, last_success_at,
-- last_failure_at, last_failure_reason are never referenced below, so
-- they are structurally impossible for this script to touch.
--
-- STATUS: NOT YET RUN. Apply via Supabase SQL Editor only after explicit
-- production-execution approval (separate from this script being
-- written) — per ChatGPT's instruction, "berhenti dan tunggu approval
-- sebelum menyentuh production."
--
-- Pre-flight (run manually before this, read-only):
--   SELECT count(*) FROM sources; -- must be ${rows.length} before running this script
--   SELECT id FROM sources WHERE id NOT IN (${idList});  -- must be 0 rows
--   SELECT id FROM (VALUES (${rows.map(r => sqlString(r.id)).join('), (')})) AS expected(id)
--     WHERE id NOT IN (SELECT id FROM sources);  -- must be 0 rows (no expected id missing from sources)
-- If either pre-flight query returns unexpected rows, STOP — do not run
-- the migration below. This is the "42/43 = rollback everything" rule
-- from the cutover plan applied before the transaction even starts.

BEGIN;

${updateStatements}

-- Fail-closed row-count assertion, inside the same transaction: if
-- fewer than ${rows.length} rows were actually touched (e.g. an id present in
-- RSS_SOURCES but missing from production \`sources\`), abort and roll
-- back everything rather than leaving a partial migration.
DO $$
DECLARE
  migrated_count INTEGER;
BEGIN
  SELECT count(*) INTO migrated_count FROM sources
    WHERE id IN (${idList}) AND status IS NOT NULL;
  IF migrated_count != ${rows.length} THEN
    RAISE EXCEPTION 'FAIL-CLOSED: expected % rows migrated, found %. Rolling back.', ${rows.length}, migrated_count;
  END IF;
END $$;

COMMIT;

-- Post-migration verification (run manually after COMMIT, read-only):
--   SELECT status, count(*) FROM sources GROUP BY status;
--     -- expected: active=${rows.length - disabledRows.length}, disabled=${disabledRows.length}
--   SELECT id, status, active FROM sources WHERE id = 'rss-kpm';
--     -- expected: status='disabled', active=false
--   SELECT id FROM sources WHERE status = 'active' AND active = false
--                              OR status != 'active' AND active = true;
--     -- expected: 0 rows (active/status invariant, §4a)
--   SELECT id, coverage, last_success_at, last_failure_at, last_failure_reason
--     FROM sources ORDER BY id;
--     -- eyeball: these 4 columns must be identical to their pre-migration
--     -- values (this script never writes them) — compare against a
--     -- snapshot taken before running this migration.
`;

mkdirSync('db/generated', { recursive: true });
const outPath = 'db/generated/source-registry-production-migration.sql';
writeFileSync(outPath, sql, 'utf8');

console.log(`✓ Generated ${outPath} (${rows.length} UPDATE statements, 1 transaction, fail-closed row-count assertion).`);
console.log(`  rss-kpm confirmed disabled, all others active — matches cutover plan §1 baseline.`);
console.log(`  Not run against any database. Awaiting separate production-execution approval.\n`);
